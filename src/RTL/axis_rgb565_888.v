// =====================================================================
//  axis_rgb565_888.v —— AXIS 位宽转换：16bit RGB565 → 24bit RGB888
//
//  ─────────────────────────────────────────────────────────────────
//  为什么需要这个模块
//  ─────────────────────────────────────────────────────────────────
//  VDMA MM2S 出的是 **16 位 RGB565**（`bd_video.tcl` 里
//  `c_m_axis_mm2s_tdata_width {16}`），而 Digilent rgb2dvi 的
//  `vid_pData` 是**固定 24 位**（`rgb2dvi_v1_2/src/rgb2dvi.vhd:79`）。
//
//  中间还夹着 `v_axi4s_vid_out`：它的 s_axis 宽度由
//  `C_S_AXIS_VIDEO_FORMAT` 决定，vid_io_out 宽度 = 分量数 ×
//  `C_NATIVE_COMPONENT_WIDTH`。要让 `vid_io_out` 出 24 位，
//  s_axis 也必须配成 24 位（FORMAT=2 + DATA_WIDTH=8）。
//
//  所以本模块插在 **VDMA → v_axi4s_vid_out** 之间，跑 100 MHz
//  （FCLK_CLK0）。v_axi4s_vid_out 配成异步（`C_HAS_ASYNC_CLK=1`）后
//  vid_io 侧才切到 74.25 MHz 像素时钟。
//
//  ─────────────────────────────────────────────────────────────────
//  ⚠⚠ 最关键的一条：输出是 **RBG** 序，不是 RGB！
//  ─────────────────────────────────────────────────────────────────
//  这是本项目最容易静默出错的地方，所以从源码查实了才写：
//
//  1. `v_axi4s_vid_out` **不做任何重排** —— 它的 `TDATA_OUT = TDATA_IN`
//     （`v_axi4s_vid_out_v4_0_vl_rfs.v:1764`，1 PPC 分支），
//     s_axis 的位序原样透传到 vid_io_out。所以位序**完全由本模块决定**。
//
//  2. `rgb2dvi` 期望的是 **RBG** 排列，源码原文
//     （`rgb2dvi_v1_2/src/rgb2dvi.vhd:181-184`）：
//
//         -- for some reason vid_data is packed in RBG order
//         pDataOut(2) <= vid_pData(23 downto 16);  -- red   is channel 2
//         pDataOut(1) <= vid_pData(7 downto 0);    -- green is channel 1
//         pDataOut(0) <= vid_pData(15 downto 8);   -- blue  is channel 0
//
//     即  [23:16] = R、[15:8] = B、[7:0] = G。**G 与 B 是反的。**
//
//  3. Digilent PYNQ base overlay 里 `v_axi4s_vid_out` 与 `rgb2dvi`
//     之间夹的那个 `color_swap` 模块，**默认参数就是
//     `input_format="rgb"` → `output_format="rbg"`** —— 干的就是这件事。
//
//  ⚠ 按"常识"写成 R-G-B 的后果：**绿蓝互换**。画面看着像对的、
//    只是颜色不对，属于本项目最怕的静默失败。
//
//  ─────────────────────────────────────────────────────────────────
//  输入侧：VDMA 的 RGB565 字节序
//  ─────────────────────────────────────────────────────────────────
//  VDMA 把 DDR 里的小端 16 位字按原样送出来。对 RGB565 而言，
//  16 位字的值本身就是 `{R[4:0], G[5:3], G[2:0], B[4:0]}`，
//  与 `dma_in` 方向 `dvp_capture` 的 `{高字节, 低字节}` 约定一致
//  （见 `src/RTL/dvp_capture.v:16-21`）。
//
//  ⚠ 若上板实测发现**红蓝互换**（不是绿蓝），说明 DDR 里的字节序
//    与此相反，把参数 `IN_BYTE_SWAP` 置 1。**不要凭猜改 ——
//    用标准彩条验证**（彩条各条颜色是已知的，一眼能看出错哪条）。
//
//  ─────────────────────────────────────────────────────────────────
//  握手：必须零延迟组合直通
//  ─────────────────────────────────────────────────────────────────
//  本模块**不加任何寄存器**，纯组合。三条理由：
//    1. `tvalid/tready/tlast` 若有延迟，SOF/EOL 会错位 → 画面撕裂
//    2. 位宽转换只是重排位，没有跨拍逻辑，不需要打拍
//    3. 省一级流水线延迟，时序更宽松
//
//  `tready` 是**组合回授**（下游 ready 直接驱动上游 ready）。
//  这正是 AXI4-Stream 允许的、也是 VDMA 期望的行为。
//
//  ─────────────────────────────────────────────────────────────────
//  ⚠ 为什么有一个用不到的 `aclk`
//  ─────────────────────────────────────────────────────────────────
//  `aclk` 在本模块的逻辑里**完全没用到**（纯组合转换），
//  但**必须存在**，否则 BD 无法把这两条 AXIS 接口关联到某个时钟域 ——
//  后果是**这两条网的时序根本不会被分析**，属于静默的时序盲区。
//  在 BD 里把它接到 FCLK_CLK0（与 VDMA 同一域，100 MHz）。
//
//  ⚠ 不要把它当成"多余端口"删掉。真要删，就得改成非模块方式接入。
// =====================================================================

`timescale 1ns / 1ps

module axis_rgb565_888 #(
    // 0 = VDMA 送出的 16 位字就是 {R,G,B} 标准打包（默认）
    // 1 = 高低字节相反，进来先交换
    parameter IN_BYTE_SWAP = 0
) (
    // BD 关联用的时钟（逻辑上未使用，见文件头说明）
    input  wire        aclk,

    // ---- 从 vdma/M_AXIS_MM2S 来（100 MHz / FCLK_CLK0 域）----
    input  wire [15:0] s_axis_tdata,
    input  wire        s_axis_tvalid,
    output wire        s_axis_tready,
    input  wire        s_axis_tlast,

    // ---- 送 v_axi4s_vid_out/video_in（同为 100 MHz）----
    output wire [23:0] m_axis_tdata,
    output wire        m_axis_tvalid,
    input  wire        m_axis_tready,
    output wire        m_axis_tlast
);

    // aclk 不参与逻辑 —— 显式"使用"它以避免综合器报 unused 警告
    wire unused_clk = aclk | 1'b0;

    // -----------------------------------------------------------------
    //  1. 拆 RGB565
    // -----------------------------------------------------------------
    wire [15:0] px = IN_BYTE_SWAP ? {s_axis_tdata[7:0], s_axis_tdata[15:8]}
                                  :  s_axis_tdata;

    wire [4:0] r5 = px[15:11];
    wire [5:0] g6 = px[10:5];
    wire [4:0] b5 = px[4:0];

    // -----------------------------------------------------------------
    //  2. 位扩展：5/6 位 → 8 位
    //
    //  用 `{原值, 原值高位}` 而不是 `{原值, 3'b000}`：
    //  把高位补到低位，使满量程仍映射到满量程
    //  （r5=31 → 255 而不是 248），避免白色发灰、灰色偏暗。
    //
    //     R5 5→8：{r5, r5[4:2]}    5+3 = 8
    //     G6 6→8：{g6, g6[5:4]}    6+2 = 8
    //     B5 5→8：{b5, b5[4:2]}    5+3 = 8
    //
    //  代价：非线性（不是严格的 ×255/31），但视觉上更接近原始亮度，
    //  是位扩展的常用做法。对「小人是纯色块」这个用途完全够。
    // -----------------------------------------------------------------
    wire [7:0] r8 = {r5, r5[4:2]};
    wire [7:0] g8 = {g6, g6[5:4]};
    wire [7:0] b8 = {b5, b5[4:2]};

    // -----------------------------------------------------------------
    //  3. 组装成 **RBG** 序（⚠ 不是 RGB！见文件头说明）
    //
    //     [23:16] = R
    //     [15: 8] = B      ← 注意这里
    //     [ 7: 0] = G
    // -----------------------------------------------------------------
    assign m_axis_tdata = {r8, b8, g8};

    // -----------------------------------------------------------------
    //  4. 握手：纯组合直通，零延迟
    // -----------------------------------------------------------------
    assign m_axis_tvalid  = s_axis_tvalid;
    assign m_axis_tlast   = s_axis_tlast;
    assign s_axis_tready  = m_axis_tready;

endmodule
